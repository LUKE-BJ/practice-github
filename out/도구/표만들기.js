// ── 2_사업정리.md 읽기 ────────────────────────────────────────────────────────────────
const md = fs.readFileSync(path.join(mid, '2_사업정리.md'), 'utf8').replace(/\r\n/g, '\n');
const sections = md.split(/^## 사업 /m).slice(1).map(s => {
  const head = s.split('\n')[0];
  const m = head.match(/^(\d+)\.\s+(.*)$/);
  const body = s;
  const pages = (body.match(/PDF 쪽 범위: ([^\n]+)/) || [])[1] || '〔확인필요〕';
  const dept = (body.match(/소관\(본문 첫머리 표기\): ([^\n]+)/) || [])[1] || '〔확인필요〕';
  const g = body.indexOf('1. 개 요');
  let overview = '〔확인필요〕';
  if (g >= 0) {
    const rest = body.slice(g);
    const e = rest.search(/\n\s*2\.\s/);
    overview = (e > 0 ? rest.slice(0, e) : rest.slice(0, 700)).split('\n').filter(l => l.trim() && !/^[ⅠⅡⅢⅣⅤⅥ]$/.test(l.trim())).join('\n').slice(0, 900).trim();
  }
  return { no: Number(m[1]), name: m[2].trim(), pages, dept, overview };
});

